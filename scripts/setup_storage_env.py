"""Interactive R2/S3 setup — writes backend/config/storage.env without echo.

Run in a normal terminal (not through chat):

    .venv\\Scripts\\python.exe scripts\\setup_storage_env.py

Press Enter to keep an existing value. The secret is read with getpass, so it
is not printed on screen or added to shell history.
"""

from __future__ import annotations

import getpass
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "backend" / "config" / "storage.env"


def existing() -> dict[str, str]:
    values: dict[str, str] = {}
    if TARGET.is_file():
        for raw in TARGET.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    return values


def ask(label: str, current: str, secret: bool = False) -> str:
    suffix = f" [{current}]" if current and not secret else ""
    if secret:
        print(f"{label}{': keep existing secret' if current else ''}")
        value = getpass.getpass("> ").strip()
    else:
        value = input(f"{label}{suffix}: ").strip()
    return value or current


def main() -> int:
    old = existing()
    account = ask(
        "Cloudflare account ID (from R2 overview)",
        old.get("S3_ENDPOINT_URL", "").split("//")[-1].split(".")[0]
        if old.get("S3_ENDPOINT_URL", "").startswith("https://")
        else "",
    )
    bucket = ask("R2 bucket name", old.get("S3_BUCKET", ""))
    access = ask("R2 access key ID", old.get("S3_ACCESS_KEY", ""))
    secret = ask("R2 secret access key", old.get("S3_SECRET_KEY", ""), secret=True)

    if not account or not bucket or not access or not secret:
        print("All four values are required.")
        return 1

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        "\n".join(
            [
                "# Generated by scripts/setup_storage_env.py — do not commit.",
                "STORAGE_BACKEND=s3",
                f"S3_ENDPOINT_URL=https://{account}.r2.cloudflarestorage.com",
                "S3_REGION=auto",
                f"S3_BUCKET={bucket}",
                f"S3_ACCESS_KEY={access}",
                f"S3_SECRET_KEY={secret}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"Wrote {TARGET}")
    print("Verifying bucket access…")
    try:
        import boto3
        from botocore.config import Config

        client = boto3.client(
            "s3",
            endpoint_url=f"https://{account}.r2.cloudflarestorage.com",
            region_name="auto",
            aws_access_key_id=access,
            aws_secret_access_key=secret,
            config=Config(signature_version="s3v4", s3={"addressing_style": "path"}),
        )
        client.head_bucket(Bucket=bucket)
        print("R2 credentials work and the bucket is reachable.")
    except Exception as exc:
        print(f"Verification failed: {exc}")
        print("The file was written; fix the values and re-run this script.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
